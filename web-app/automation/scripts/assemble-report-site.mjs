import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const report = path.join(root, "allure-report");
const artifacts = path.join(root, "artifacts", "k6");
const templates = path.join(root, "reporter");
await fs.mkdir(report, { recursive: true });
await fs.mkdir(path.join(report, "assets"), { recursive: true });
for (const file of ["report-home.html", "performance-report.html"]) {
  await fs.copyFile(path.join(templates, file), path.join(report, file));
}
await fs.copyFile(path.join(templates, "native-k6-report.html"), path.join(report, "native-k6-report.html"));
try { await fs.copyFile(path.join(root, "db-report", "index.html"), path.join(report, "db-report.html")); } catch { /* Database report is generated by the report builder when results are available. */ }
for (const file of ["k6-summary.json", "k6-raw-summary.json", "native-k6-report.html"]) {
  try {
    await fs.copyFile(path.join(artifacts, file), path.join(report, file));
  } catch {
    // The first report has linked pages but no k6 run data yet.
  }
}
